package co.edu.unipiloto.plataforma.dto;

import co.edu.unipiloto.plataforma.modelo.EstadoCertificado;
import java.time.LocalDateTime;

public class CertificadoResponse {

    private Long id;

    private String codigo;

    private Long estudianteId;

    private String estudianteNombre;

    private Long cursoId;

    private String cursoTitulo;

    private Double notaFinal;

    private EstadoCertificado estado;

    private LocalDateTime fechaSolicitud;

    private LocalDateTime fechaEmision;

    public Long getId() { return id; }
    public void setId(Long id) { this.id = id; }

    public String getCodigo() { return codigo; }
    public void setCodigo(String codigo) { this.codigo = codigo; }

    public Long getEstudianteId() { return estudianteId; }
    public void setEstudianteId(Long estudianteId) { this.estudianteId = estudianteId; }

    public String getEstudianteNombre() { return estudianteNombre; }
    public void setEstudianteNombre(String estudianteNombre) { this.estudianteNombre = estudianteNombre; }

    public Long getCursoId() { return cursoId; }
    public void setCursoId(Long cursoId) { this.cursoId = cursoId; }

    public String getCursoTitulo() { return cursoTitulo; }
    public void setCursoTitulo(String cursoTitulo) { this.cursoTitulo = cursoTitulo; }

    public Double getNotaFinal() { return notaFinal; }
    public void setNotaFinal(Double notaFinal) { this.notaFinal = notaFinal; }

    public EstadoCertificado getEstado() { return estado; }
    public void setEstado(EstadoCertificado estado) { this.estado = estado; }

    public LocalDateTime getFechaSolicitud() { return fechaSolicitud; }
    public void setFechaSolicitud(LocalDateTime fechaSolicitud) { this.fechaSolicitud = fechaSolicitud; }

    public LocalDateTime getFechaEmision() { return fechaEmision; }
    public void setFechaEmision(LocalDateTime fechaEmision) { this.fechaEmision = fechaEmision; }

}
